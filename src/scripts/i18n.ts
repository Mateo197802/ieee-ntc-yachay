export const EN_TO_ES_MAP: Record<string, string> = {};
for (const [es, en] of Object.entries(ES_TO_EN_MAP)) {
  EN_TO_ES_MAP[en] = es;
}

export function getCurrentLanguage(): 'es' | 'en' {
  if (typeof window === 'undefined') return 'es';
  const saved = localStorage.getItem('ntc_lang');
  return (saved === 'en' || saved === 'es') ? saved : 'es';
}

function replaceTextInString(text: string, lang: 'es' | 'en'): string {
  if (!text) return text;
  let result = text;

  if (lang === 'en') {
    // Dynamic subnav counter patterns
    result = result.replace(/Próximos Eventos\s*\((\d+)\)/g, 'Upcoming Events ($1)');
    result = result.replace(/Eventos Pasados\s*\((\d+)\)/g, 'Past Events ($1)');
    result = result.replace(/Foto\s+(\d+)\s+de\s+(\d+)/g, 'Photo $1 of $2');

    // Known map lookup
    for (const [es, en] of Object.entries(ES_TO_EN_MAP)) {
      if (result.includes(es)) {
        result = result.replaceAll(es, en);
      }
    }
  } else {
    // Dynamic subnav counter patterns
    result = result.replace(/Upcoming Events\s*\((\d+)\)/g, 'Próximos Eventos ($1)');
    result = result.replace(/Past Events\s*\((\d+)\)/g, 'Eventos Pasados ($1)');
    result = result.replace(/Photo\s+(\d+)\s+of\s+(\d+)/g, 'Foto $1 de $2');

    // Known map lookup
    for (const [en, es] of Object.entries(EN_TO_ES_MAP)) {
      if (result.includes(en)) {
        result = result.replaceAll(en, es);
      }
    }
  }

  return result;
}

export function setLanguage(lang: 'es' | 'en') {
  if (typeof window === 'undefined') return;
  localStorage.setItem('ntc_lang', lang);
  document.documentElement.lang = lang;

  // Update active buttons in header/mobile
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Walk text nodes in the DOM
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (tag === 'script' || tag === 'style' || tag === 'noscript') return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  let currentNode = walker.nextNode();
  while (currentNode) {
    const rawText = currentNode.nodeValue;
    if (rawText && rawText.trim().length > 0) {
      const transformed = replaceTextInString(rawText, lang);
      if (transformed !== rawText) {
        currentNode.nodeValue = transformed;
      }
    }
    currentNode = walker.nextNode();
  }
}

export function initI18n() {
  if (typeof window === 'undefined') return;
  
  const initialLang = getCurrentLanguage();
  document.documentElement.lang = initialLang;

  // Bind click handlers to language toggle buttons
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.addEventListener('click', () => {
      const targetLang = (btn.getAttribute('data-lang') || 'es') as 'es' | 'en';
      setLanguage(targetLang);
    });
  });

  if (initialLang === 'en') {
    setLanguage('en');
  } else {
    setLanguage('es');
  }
}
