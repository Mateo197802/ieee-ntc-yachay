export const REVERSE_DICTIONARY: Record<string, string> = {};
for (const [es, en] of Object.entries(EXACT_PHRASE_DICTIONARY)) {
  REVERSE_DICTIONARY[en] = es;
}

export function getCurrentLanguage(): 'es' | 'en' {
  if (typeof window === 'undefined') return 'es';
  const saved = localStorage.getItem('ntc_lang');
  return (saved === 'en' || saved === 'es') ? saved : 'es';
}

export function setLanguage(lang: 'es' | 'en') {
  if (typeof window === 'undefined') return;
  localStorage.setItem('ntc_lang', lang);
  document.documentElement.lang = lang;

  // 1. Update active button styles
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // 2. Attribute-based instant translation (Highest Priority & Full Fidelity)
  const textAttr = `data-i18n-${lang}`;
  document.querySelectorAll(`[${textAttr}]`).forEach((el) => {
    const val = el.getAttribute(textAttr);
    if (val !== null && val !== undefined && val.trim().length > 0) {
      el.textContent = val;
    }
  });

  const htmlAttr = `data-i18n-html-${lang}`;
  document.querySelectorAll(`[${htmlAttr}]`).forEach((el) => {
    const val = el.getAttribute(htmlAttr);
    if (val !== null && val !== undefined && val.trim().length > 0) {
      el.innerHTML = val;
    }
  });

  const placeholderAttr = `data-i18n-placeholder-${lang}`;
  document.querySelectorAll(`[${placeholderAttr}]`).forEach((el) => {
    const val = el.getAttribute(placeholderAttr);
    if (val) (el as HTMLInputElement).placeholder = val;
  });

  const ariaAttr = `data-i18n-aria-${lang}`;
  document.querySelectorAll(`[${ariaAttr}]`).forEach((el) => {
    const val = el.getAttribute(ariaAttr);
    if (val) el.setAttribute('aria-label', val);
  });

  // 3. Fallback: Exact dictionary translation on any remaining text nodes
  const dict = lang === 'en' ? EXACT_PHRASE_DICTIONARY : REVERSE_DICTIONARY;
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (tag === 'script' || tag === 'style' || tag === 'noscript') return NodeFilter.FILTER_REJECT;
        // Skip elements that already handled via data-attributes
        if (parent.hasAttribute(textAttr) || parent.hasAttribute(htmlAttr)) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  let currentNode = walker.nextNode();
  while (currentNode) {
    const raw = currentNode.nodeValue?.trim() || '';
    if (raw && dict[raw]) {
      currentNode.nodeValue = currentNode.nodeValue!.replace(raw, dict[raw]);
    }
    currentNode = walker.nextNode();
  }
}

export function initI18n() {
  if (typeof window === 'undefined') return;
  
  const currentLang = getCurrentLanguage();
  setLanguage(currentLang);

  // Global click event delegation for language switcher buttons
  document.addEventListener('click', (e) => {
    const target = e.target as HTMLElement | null;
    const btn = target?.closest('.lang-btn') as HTMLElement | null;
    if (btn) {
      e.preventDefault();
      const targetLang = (btn.getAttribute('data-lang') || 'es') as 'es' | 'en';
      setLanguage(targetLang);
    }
  });
}
